from app.classifier.lexical import LexicalIndex, rrf, tokens


def test_tokens_match_word_forms():
    # «плиты»/«плита», «легковые»/«легковой» дают одинаковые основы, предлоги и числа отбрасываются
    assert tokens("Плиты древесно-стружечные") == tokens("плита древесно-стружечная 16")
    assert tokens("Автомобили легковые") == tokens("автомобиль легковой")
    assert tokens("для дома 500") == ["дом"]


def test_tokens_keep_different_words_apart():
    assert tokens("металлические") != tokens("металлизированная")


def test_bm25_prefers_rare_matching_words():
    idx = LexicalIndex([
        ("16.21.13.000", "Плиты древесно-стружечные и аналогичные плиты из древесины"),
        ("27.51.28.110", "Плиты кухонные"),
        ("32.50.50.190", "Изделия медицинские прочие"),
        ("32.50.50.150", "Изделия медицинские для оториноларингологии"),
        ("32.50.50.140", "Изделия медицинские урологические"),
        ("32.50.30.110", "Мебель медицинская"),
        ("32.50.13.110", "Шприцы, иглы, катетеры, канюли и аналогичные инструменты"),
        # как в справочнике: «изделия медицинские» — в сотнях наименований
        *[(f"32.50.50.{i:03d}", f"Изделия медицинские группы {i}") for i in range(20)],
    ])
    assert idx.search("плита древесно-стружечная 16 мм", 2)[0][0] == "16.21.13.000"
    # «медицинские изделия» встречаются во многих текстах и весят мало, «катетер» — редкое слово и решает
    assert idx.search("катетер уретральный медицинское изделие", 1)[0][0] == "32.50.13.110"
    assert idx.search("абракадабра", 5) == []


def test_bm25_best_text_per_code():
    idx = LexicalIndex([("16.21.13.000", "Плиты древесно-стружечные"), ("16.21.13.000", "дсп")])
    assert [c for c, _, _ in idx.search("плита дсп", 5)] == ["16.21.13.000"]


def test_rrf_fuses_and_weights_lists():
    # c: 1/61 + 1/63 чуть больше, чем b: 2/62
    assert rrf([["a", "b", "c"], ["c", "b"]]) == ["c", "b", "a"]
    assert rrf([["a", "b"], ["b"]], weights=[1.0, 0.0])[0] == "a"
