/** Уверенность в процентах — с округлением вниз: при пороге «проверьте вручную» 80% значение 0.7964
 *  должно показываться как 79%, а не 80% (иначе строка с пометкой выглядит как «80% — уверена»).
 *  +1e-9 гасит ошибку представления: 0.29 * 100 = 28.999999999999996. */
export function confidencePct(value: number): number {
  return Math.floor(value * 100 + 1e-9);
}
