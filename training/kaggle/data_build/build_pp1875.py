REGIME = {"1": "запрет", "2": "ограничение", "3": "минимальная обязательная доля (223-ФЗ)"}
URL = {"1": "https://www.consultant.ru/document/cons_doc_LAW_494318/dc1993c2b5c2478f2ab15f73dba12882e6b458c8/",
       "2": "https://www.consultant.ru/document/cons_doc_LAW_494318/b0541e42afa5defcd0520054f0979f05aff711fb/",
       "3": "https://www.consultant.ru/document/cons_doc_LAW_494318/3040cb5a1945ab3d2bbe52797e35a36534993493/"}
# сроки применения из примечаний КонсультантПлюс (ред. 30.09.2026)
EFF = {("2", i): "01.01.2027" for i in ["82(1)", "109(1)", "109(2)", "110(1)", "110(2)", "110(3)", "113", "113(1)", "113(2)"]}
EFF[("2", "104(1)")] = "01.07.2026"
EXCL = {("2", "205"): "26.20.40.150"}
NOTE_EXC = {("1", "146"): "только программы для ЭВМ и базы данных: коды 61-64 указаны целыми разделами, "
                          "но услуги связи, ИТ-услуги и т.п. под позицию не подпадают"}  # «за исключением устройств ЧПУ ... 26.20.40.150» (они в прил. 1, поз. 27)

out = []
for r in rows:
    k = (r["appendix"], r["item"])
    out.append(dict(appendix=r["appendix"], item=r["item"], okpd2=r["okpd2"], name=r["name"],
                    regime=REGIME[r["appendix"]], min_share=r["min_share"], excl_okpd2=EXCL.get(k, ""),
                    exceptions=NOTE_EXC.get(k, "код указан «из …»: позиция охватывает только часть товаров этого кода" if r["partial_code"] else ""),
                    effective_from=EFF.get(k, ""), note=r["note"], url=URL[r["appendix"]],
                    source="Контур.Норматив, ред. 03.08.2026"))

def add(app, item, okpd2, name, eff, note, exceptions="", share="", after=None):
    row = dict(appendix=app, item=item, okpd2=okpd2, name=name, regime=REGIME[app], min_share=share,
               excl_okpd2="", exceptions=exceptions, effective_from=eff, note=note, url=URL[app], source=note)
    idx = next(i for i, r in enumerate(out) if r["appendix"] == app and r["item"] == after) + 1 if after else \
          max(i for i, r in enumerate(out) if r["appendix"] == app) + 1
    out.insert(idx, row)

# ПП от 25.09.2026 N 1236 (с 01.10.2026)
n1236 = "введена Постановлением Правительства РФ от 25.09.2026 N 1236"
