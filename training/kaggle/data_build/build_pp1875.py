"""Сборка pp1875.csv: база = Контур.Норматив (ред. 03.08.2026, перенос сверен SHA-256)
+ поправки ПП от 21.09.2026 N 1201, от 25.09.2026 N 1236, от 30.09.2026 N 1264 (тексты прочитаны на kontur-extern.ru)."""
